"""Generate the SDK's face registration from the matching felt frame calibrations."""

import json
from pathlib import Path
import sys


def fields(values, names, size):
    if len(values) != size:
        raise ValueError(f"Expected {size} coordinates, got {values!r}")
    return ", ".join(
        f"{name}: {value:g}" if name else f"{value:g}"
        for name, value in zip(names, values)
    )


def eye(values):
    return f".init({fields(values, ('', '', '', ''), 4)})" if values else "nil"


def emit_face(entry):
    bounds = fields(entry["bounds"], ("x", "y", "width", "height"), 4)
    muzzle = fields(entry["muzzle"], ("", "", "", "", "mouthX", "mouthY"), 6)
    return (
        f"    .init(.init({bounds}),\n"
        f"      left: {eye(entry['left'])}, right: {eye(entry['right'])},\n"
        f"      muzzle: .init({muzzle}), eyeAngle: {entry['eyeAngle']:g}),"
    )


def main():
    source_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("Transitions")
    routes = {
        "left": "left", "right": "right", "stretch": "stretch",
        "bellyUp": "belly", "puffedRight": "puffright", "rear": "rear",
    }
    sections = []
    for route, file_stem in routes.items():
        frames = json.loads((source_dir / f"{file_stem}-face.json").read_text())
        expected = 4 if route == "puffedRight" else 11
        if len(frames) != expected:
            raise ValueError(f"Expected {expected} registered faces for {route}")
        sections.append(f"  private static let {route}: [Face] = [\n" + "\n".join(
            map(emit_face, frames)
        ) + "\n  ]")

    print("// Generated by Artwork/FullBodyCat/emit_transition_faces.py from the frame calibrations.")
    print("enum CharacterFeltCatTransitionRegistration {")
    print("  typealias Face = CharacterFullBodyCatArtwork.Face\n")
    print("  static func frames(for route: CharacterFeltCatTransition.Route) -> [Face] {")
    print("    switch route {")
    for route in routes:
        print(f"    case .{route}: {route}")
    print("    case .loaf, .waving, .upright, .puffed: []")
    print("    }\n  }\n")
    print("\n\n".join(sections))
    print("}")


if __name__ == "__main__":
    main()
